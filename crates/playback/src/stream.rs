//! Sentence stream state without clock reads or I/O. A transport executes each
//! action and acknowledges successful dispatch before advancing this stream.
//!
//! [`SentenceStream`](crate::stream::SentenceStream) accepts already-converted
//! mono 8 kHz mu-law bytes and queues [`Action`](crate::stream::Action) values.
//! It frames full 160-byte/20 ms media packets, flushes short tails unchanged,
//! adds sentence/end marks and limits queued audio lead using injected time.
//! The host owns provider reads, ambience mixing, waits, network sends and retries.
use std::collections::VecDeque;
use serde::{Serialize, Deserialize};
use crate::sentences::split_sentences;

/// Work offered to the transport by a sentence stream.
///
/// Queued media, mark, cancel and clear actions remain pending until acknowledged
/// after successful execution. A wait is generated by pacing and is not a queue
/// entry: acknowledging it would incorrectly consume the unsent front action.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
#[serde(tag="kind",rename_all="snake_case")]
pub enum Action {
    /// Dispatch one audio packet; successful execution must be acknowledged.
    Media {
        /// Already-converted mu-law audio bytes; the stream performs no resampling/encoding.
        data:Vec<u8>,
        /// Whether the host should apply ambience mixing; false preserves short tails unchanged.
        mix:bool
    },
    /// Send a transport mark after the preceding media; acknowledgement records the send only.
    Mark {
        /// Generated sentence or terminal mark identity scoped by the audio ID.
        name:String,
        /// Short text context for the host's mark registry and diagnostics.
        snippet:String
    },
    /// Delay and call `next` again with updated time; this synthetic action must not be acknowledged.
    Wait {
        /// Remaining delay in seconds before the front full-size media packet may be sent.
        seconds:f64
    },
    /// Stop the provider session; the host owns cancellation and completion handling.
    CancelProvider,
    /// Clear already-buffered transport playback and update receipt/AEC state in the host.
    Clear,
}

/// Per-playout owner of provider-byte buffering, pacing and send-based accounting.
///
/// The host alternates pushing a provider chunk with executing/acknowledging
/// all pending actions. `next` offers an action without consuming it; only
/// `acknowledge` advances send counters. This type does not own a provider,
/// socket, clock, mixer or receipt map. Public counters are observations;
/// mutating them directly bypasses the action protocol.
pub struct SentenceStream {
    /// Sentence plan created with the 25-character short-fragment threshold.
    pub sentences:Vec<String>,
    /// Prefix length inferred from successfully dispatched sentence marks.
    pub sentences_sent:usize,
    /// Count of successfully acknowledged media packets, including short tails.
    pub chunks_sent:usize,
    /// Acknowledged media-byte total used to estimate buffered lead at eight bytes per ms.
    pub total_sent_bytes:usize,
    /// Whether graceful yield reached a sentence transition and stopped further provider input.
    pub yielded:bool,
    /// Whether immediate caller cancellation discarded pending bytes/actions.
    pub cancelled:bool,
    /// Identity embedded into generated sentence and terminal mark names.
    audio_id:String,
    /// Full original response text used for terminal-mark diagnostic context.
    text:String,
    /// Maximum intended send-ahead budget in milliseconds before a full packet must wait.
    lead_ms:f64,
    /// Monotonic time of the first full media packet offered for pacing, in seconds.
    first_frame_t:Option<f64>,
    /// Current provider sentence index; the host supplies segment order.
    segment:usize,
    /// Bytes not yet queued as a full packet, flushed at the next sentence boundary.
    pending:Vec<u8>,
    /// Ordered media/mark/cancel/clear work waiting for successful host execution.
    actions:VecDeque<Action>,
    /// Request to stop when a subsequent provider chunk crosses a sentence boundary.
    graceful_yield:bool,
    /// Whether finish has queued the terminal mark; queued actions may still remain.
    ended:bool,
    /// Monotonic time at which a paced front packet may be retried without another wait.
    release_at:Option<f64>,
}
impl SentenceStream {
    /// Create a stream for text/audio identity with the supplied millisecond lead budget.
    ///
    /// Split text using the sentence helper and a 25-character minimum. No provider
    /// read or action is started by construction; the host admits appropriate
    /// response text and supplies preconverted 8 kHz mu-law bytes through `push`.
    pub fn new(text:String, audio_id:String, lead_ms:f64) -> Self {
        Self {sentences:split_sentences(&text,25),sentences_sent:0,chunks_sent:0,total_sent_bytes:0,yielded:false,cancelled:false,
            audio_id,text,lead_ms,first_frame_t:None,segment:0,pending:vec![],actions:VecDeque::new(),graceful_yield:false,ended:false,release_at:None}
    }
    /// Latch a graceful-yield request to stop at the next provider sentence transition.
    ///
    /// This does not immediately cancel or clear audio. The current sentence
    /// continues until `push` observes a different segment index.
    pub fn request_yield(&mut self) { self.graceful_yield=true; }
    /// Queue any short pending tail unchanged, followed by the current sentence mark.
    ///
    /// The mark carries up to 80 characters of sentence context. Counters remain
    /// unchanged until the host acknowledges the generated actions.
    fn boundary(&mut self) {
        if !self.pending.is_empty() { self.actions.push_back(Action::Media {data:std::mem::take(&mut self.pending),mix:false}); }
        self.actions.push_back(Action::Mark {name:format!("tts_s{}_{}",self.segment,self.audio_id),
            snippet:self.sentences.get(self.segment).map(|s|s.chars().take(80).collect()).unwrap_or_default()});
    }
    /// Accept bytes from one provider sentence and queue full 160-byte audio packets.
    ///
    /// A changed segment first flushes the previous tail/mark. If graceful yield
    /// is pending, queue provider cancellation and discard this incoming chunk
    /// instead of buffering the new sentence. Otherwise retain a sub-frame tail
    /// and flag complete packets for host ambience mixing. Empty chunks are valid.
    ///
    /// Return an error before accepting data when the stream is terminal, earlier
    /// actions are undispatched, or the segment is outside the sentence plan.
    /// Bounds are checked; segment ordering remains the provider/host contract.
    pub fn push(&mut self, segment:usize, chunk:&[u8]) -> Result<(), &'static str> {
        if self.ended || self.cancelled || self.yielded { return Err("stream is terminal"); }
        if !self.actions.is_empty() { return Err("dispatch pending actions before next provider chunk"); }
        if segment >= self.sentences.len() { return Err("provider segment out of range"); }
        if segment != self.segment {
            self.boundary(); self.segment=segment;
            if self.graceful_yield {
                self.actions.push_back(Action::CancelProvider); self.yielded=true; return Ok(());
            }
        }
        self.pending.extend_from_slice(chunk);
        let count=self.pending.len()/160;
        for frame in self.pending[..count*160].chunks_exact(160) {
            self.actions.push_back(Action::Media {data:frame.to_vec(),mix:true});
        }
        self.pending.drain(..count*160);
        Ok(())
    }
    /// Signal provider EOF and queue final sentence/end marks after earlier actions drain.
    ///
    /// For a non-yielded, nonempty plan, flush the current tail and sentence mark.
    /// Always queue the terminal mark for an active attempt, including after a
    /// graceful yield, then mark input as ended. Already-ended/cancelled streams
    /// return success without adding actions; outstanding actions otherwise cause
    /// an error. The terminal mark still requires host execution and acknowledgement.
    pub fn finish(&mut self) -> Result<(), &'static str> {
        if self.ended || self.cancelled { return Ok(()); }
        if !self.actions.is_empty() { return Err("dispatch pending actions before finishing"); }
        if !self.yielded && !self.sentences.is_empty() { self.boundary(); }
        let mut snippet:String=self.text.chars().take(80).collect();
        if self.text.chars().count()>80 {snippet.push('…');}
        self.actions.push_back(Action::Mark {name:format!("tts_end_{}",self.audio_id),snippet});
        self.ended=true; Ok(())
    }
    /// Discard unsent actions and bytes, then queue provider cancellation and transport clear.
    ///
    /// Set the cancelled flag and remove a pacing wait. Already-dispatched counts
    /// remain intact. The host must execute both queued actions and reconcile
    /// receipt/AEC state; this method does not perform those side effects.
    pub fn cancel(&mut self) {
        self.actions.clear(); self.pending.clear(); self.cancelled=true; self.release_at=None;
        self.actions.push_back(Action::CancelProvider); self.actions.push_back(Action::Clear);
    }
    /// Offer the next host action using `now` in monotonic seconds, without consuming it.
    ///
    /// For full packets, compare acknowledged audio duration with elapsed wall
    /// time and the lead budget. Return a synthetic wait until the release time
    /// when sending is too far ahead. Short tails and non-media actions bypass
    /// this pacing check. Return None when there is no queued work.
    ///
    /// After a wait, update time and call again without acknowledging. After any
    /// queued action succeeds, acknowledge it; on failure, the host owns retry or
    /// cancellation while the front action remains pending.
    pub fn next(&mut self, now:f64) -> Option<Action> {
        let action=self.actions.front()?.clone();
        if matches!(action,Action::Media {mix:true,..}) {
            if let Some(release)=self.release_at {
                return if now<release {Some(Action::Wait {seconds:release-now})} else {Some(action)};
            }
            let first=*self.first_frame_t.get_or_insert(now);
            let ahead=self.total_sent_bytes as f64/8.0-(now-first)*1000.0;
            if ahead>self.lead_ms {
                let seconds=(ahead-self.lead_ms)/1000.0; self.release_at=Some(now+seconds);
                return Some(Action::Wait {seconds});
            }
        }
        Some(action)
    }
    /// Consume the front queued action after the host has executed it successfully.
    ///
    /// Return the consumed action, or None if empty, and clear its pacing deadline.
    /// Media updates byte/chunk counts; a sentence mark advances the sent-sentence
    /// prefix. This is send acknowledgement, not a playback echo. Never call this
    /// for a synthetic wait or failed action: it would consume unsent work.
    pub fn acknowledge(&mut self) -> Option<Action> {
        let action=self.actions.pop_front()?;
        self.release_at=None;
        match &action {
            Action::Media {data,..} => {self.chunks_sent+=1;self.total_sent_bytes+=data.len();},
            Action::Mark {name,..} if name.starts_with("tts_s") => {
                let prefix=name.strip_prefix("tts_s").unwrap().split('_').next().unwrap();
                self.sentences_sent=prefix.parse::<usize>().unwrap()+1;
            }, _=>{},
        }
        Some(action)
    }
    /// Join the prefix of sentences whose marks were successfully dispatched.
    ///
    /// The historical name denotes a send-based delivery estimate, not receipt
    /// confirmation. Clamp the public counter to the plan length; use `PlayoutState`
    /// for mark-echo-based audible progress.
    pub fn heard_text(&self) -> String {self.sentences[..self.sentences_sent.min(self.sentences.len())].join(" ")}
}
